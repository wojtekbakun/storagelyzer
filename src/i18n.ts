  override === "pl" ? "pl-PL" : override === "en" ? (systemLocale.startsWith("en") ? systemLocale : "en-US") : systemLocale;
const isPl = locale.toLowerCase().startsWith("pl");
const dict: Dict = isPl ? pl : en;

export const currentLang: "pl" | "en" = isPl ? "pl" : "en";

export function setLang(lang: "pl" | "en") {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    /* storage unavailable */
  }
  window.location.reload();
}

export type TKey = keyof Dict;

export function t(key: TKey, vars?: Record<string, string | number>): string {
  let s = dict[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

const pluralRules = new Intl.PluralRules(isPl ? "pl" : "en");

const nouns: Record<string, { pl: Record<string, string>; en: Record<string, string> }> = {
  item: {
    pl: { one: "element", few: "elementy", many: "elementów", other: "elementu" },
    en: { one: "item", other: "items" },
  },
  file: {
    pl: { one: "plik", few: "pliki", many: "plików", other: "pliku" },
    en: { one: "file", other: "files" },
  },
  folder: {
    pl: { one: "folder", few: "foldery", many: "folderów", other: "folderu" },
    en: { one: "folder", other: "folders" },
  },
};

export function plural(noun: keyof typeof nouns, count: number): string {
  const forms = isPl ? nouns[noun].pl : nouns[noun].en;
  const cat = pluralRules.select(count);
  return forms[cat] ?? forms.other;
}
